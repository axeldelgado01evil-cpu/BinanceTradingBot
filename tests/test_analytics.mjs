import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {stripTypeScriptTypes} from 'node:module';
const text=stripTypeScriptTypes(await readFile(new URL('../supabase/functions/market-bot/analytics.ts',import.meta.url),'utf8'));
const a=await import('data:text/javascript;base64,'+Buffer.from(text).toString('base64'));
const fill=(id,buy,qty,price,fee=0,feeAsset='USDT')=>a.normalizeFill({id,isBuyer:buy,qty,price,quoteQty:qty*price,commission:fee,commissionAsset:feeAsset,time:1000+id},'BTCUSDT');
const history=[fill(1,true,1,100,1),fill(2,true,1,200,1),fill(3,false,1,250,1)];
const l=a.ledger([...history,history[0]],[{asset:'BTC',amount:1,price:220}],['BTCUSDT']);
assert.equal(l.rows[0].cost,151);assert.equal(l.realized,98);assert.equal(l.unrealized,69);assert.equal(l.rows[0].trades,3);
assert.equal(a.ledger(history,[{asset:'BTC',amount:2,price:220}],['BTCUSDT']).rows[0].cost,null,'deposit must not create invented cost basis');
assert.equal(a.ledger([fill(1,false,1,200)],[],['BTCUSDT']).realized,null,'unknown opening inventory cannot have invented profit');
assert.equal(a.ledger([fill(1,true,1,100,.1,'BNB')],[{asset:'BTC',amount:1,price:220}],['BTCUSDT']).complete,false);
assert.equal(a.ledger([fill(1,true,1,100,.01,'BTC')],[{asset:'BTC',amount:.99,price:220}],['BTCUSDT']).rows[0].cost,100);
const h=[{asset:'BTC',amount:1,price:100}];const r=a.portfolioRisk(h);assert.equal(r.notices.length,1);
assert.equal(a.portfolioRisk([{...h[0],price:80}],r).drawdown,20);
assert.equal(a.portfolioRisk([{...h[0],amount:.5}],r).drawdown,0,'withdrawal resets valuation baseline');
assert.equal(a.correlation(Array.from({length:30},(_,i)=>i),Array.from({length:30},(_,i)=>i)),1);
assert.equal(a.securityReview({code:1,result:{'0xabc':{is_honeypot:'1'}}},'ethereum','0xabc').state,'risk');
assert.equal(a.securityReview({code:1,result:{'0xabc':{}}},'ethereum','0xabc').state,'unverified');
assert.equal(a.dueAlert('x','test',{x:100000},110000),null);
assert.ok(a.dueAlert('x','test',{x:100000},4000000));
console.log('Analytics passed: ledger fees/dedupe/unknown costs, transfer baseline, exposure, correlation, security unknowns, alert cooldown.');
