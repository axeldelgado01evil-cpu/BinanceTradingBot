import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {stripTypeScriptTypes} from 'node:module';
const src=stripTypeScriptTypes(await readFile(new URL('../supabase/functions/market-bot/backtest.ts',import.meta.url),'utf8'));
const {historicalSignal,runHistorical}=await import('data:text/javascript;base64,'+Buffer.from(src).toString('base64'));
const t0=1700000000000,h=4*3600000,day=86400000;
const make=(n,step)=>Array.from({length:n},(_,i)=>({time:t0+i*step,end:t0+(i+1)*step-1,open:100,high:101,low:99,close:100,volume:100}));
const four=make(650,h),daily=make(120,day),before=historicalSignal(four,daily,400);
const changed=structuredClone(four);for(let i=401;i<changed.length;i++)changed[i].close=100000;
const future=structuredClone(daily);for(const d of future)if(d.end>four[400].end)d.close=100000;
assert.deepEqual(historicalSignal(changed,future,400),before,'future bars cannot affect a historical signal');
const data=Object.fromEntries(['BTCUSDT','ETHUSDT','SOLUSDT'].map(s=>[s,{four:structuredClone(four),daily:structuredClone(daily)}]));
const result=runHistorical(data,four[400].time,four[649].end);
assert.equal(result.closedTrades,0);assert.equal(result.final,100);assert.equal(result.evidence,'insufficient_sample');
assert.ok(result.benchmark<100,'benchmark pays entry fee and spread');
const gap=structuredClone(data);gap.SOLUSDT.four.pop();
assert.equal(runHistorical(gap,four[400].time,four[649].end).missingBars,1);
assert.ok(runHistorical(gap,four[400].time,four[649].end).benchmark>99,'a missing last bar must not zero a benchmark holding');
console.log('Backtest checks passed: future-data isolation, zero-signal baseline, costs, missing-bar handling.');
