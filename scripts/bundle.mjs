// Dependency-free packaging for the Supabase dashboard single-file editor.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {stripTypeScriptTypes} from 'node:module';
const dir=new URL('../supabase/functions/market-bot/',import.meta.url);
let output='// Generated by scripts/bundle.mjs; readable sources are in the repository.\n';
for(const name of ['analytics','enhancements','interaction','index']){
 let code=stripTypeScriptTypes(await readFile(new URL(name+'.ts',dir),'utf8'));
 code=code.replace(/import\s*\{([^}]+)\}\s*from\s*['"]\.\/(\w+)\.ts['"];?/g,(_,names,mod)=>`const {${names}}=__${mod};`);
 const exports=[...code.matchAll(/export\s+(?:async\s+)?(?:function|const|class)\s+(\w+)/g)].map(m=>m[1]);
 code=code.replace(/\bexport\s+/g,'');
 output+=`const __${name}=(()=>{\n${code}\nreturn {${exports.join(',')}};\n})();\n`;
}
await mkdir(new URL('../.cache/deploy/',import.meta.url),{recursive:true});
await writeFile(new URL('../.cache/deploy/market-bot.js',import.meta.url),output);
console.log('Bundled market-bot, '+output.length+' characters');
